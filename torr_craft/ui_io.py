"""Import / export of Torr Craft schematics as Qt Designer ``.ui`` XML."""

import os
import re
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

from . import __version__
from .device_specs import CLASS_TO_KEY, DEVICE_SPECS, PALETTE_ORDER
from .document import (
    CANVAS_HEIGHT,
    CANVAS_WIDTH,
    ComponentData,
    DocumentData,
    PipeData,
)
from .components.pipe import (
    ROUTE_MODES,
    decode_bend_points,
    encode_bend_points,
)
from .topology import unisolated_chamber_pair

MAX_FILE_BYTES = 8 * 1024 * 1024
MAX_COMPONENTS = 500
MAX_PIPES = 800
APP_MARKER = "Torr Craft"


class UiFormatError(ValueError):
    """Raised when a file is not a readable Torr Craft / Qt .ui document."""


def _local(tag):
    return tag.rsplit("}", 1)[-1] if "}" in tag else tag


def _find_property(widget, name):
    for prop in widget.findall("property"):
        if prop.get("name") == name:
            for child in list(prop):
                return child
    return None


def _prop_text(widget, name, default=""):
    node = _find_property(widget, name)
    if node is None:
        return default
    text = node.text
    return default if text is None else text.strip()


def _prop_bool(widget, name, default=False):
    node = _find_property(widget, name)
    if node is None:
        return default
    text = (node.text or "").strip().lower()
    if text in ("1", "true", "yes", "on"):
        return True
    if text in ("0", "false", "no", "off"):
        return False
    return default


def _prop_int(widget, name, default=0):
    node = _find_property(widget, name)
    if node is None:
        return default
    try:
        return int(float((node.text or "").strip()))
    except (TypeError, ValueError):
        return default


def _prop_float(widget, name, default=0.0):
    node = _find_property(widget, name)
    if node is None:
        return default
    try:
        return float((node.text or "").strip())
    except (TypeError, ValueError):
        return default


def _prop_rect(widget):
    node = _find_property(widget, "geometry")
    if node is None:
        return None
    rect = node if _local(node.tag) == "rect" else node.find("rect")
    if rect is None:
        return None
    try:
        return (
            int(float(rect.findtext("x", "0"))),
            int(float(rect.findtext("y", "0"))),
            int(float(rect.findtext("width", "0"))),
            int(float(rect.findtext("height", "0"))),
        )
    except (TypeError, ValueError):
        return None


def _add_property(parent, name, value, kind="string", dynamic=False):
    attrs = {"name": name}
    if dynamic:
        attrs["stdset"] = "0"
    prop = ET.SubElement(parent, "property", attrs)
    node = ET.SubElement(prop, kind)
    if kind == "bool":
        node.text = "true" if value else "false"
    else:
        node.text = str(value)
    return prop


def _add_rect(parent, x, y, width, height):
    prop = ET.SubElement(parent, "property", {"name": "geometry"})
    rect = ET.SubElement(prop, "rect")
    for key, value in (("x", x), ("y", y), ("width", width), ("height", height)):
        ET.SubElement(rect, key).text = str(int(value))


def _pipe_bounds(pipe, components):
    a = components.get(pipe.source_id)
    b = components.get(pipe.target_id)
    if a is None or b is None:
        return 0, 0, 0, 0
    left = min(a.x, b.x)
    top = min(a.y, b.y)
    right = max(a.x + a.width, b.x + b.width)
    bottom = max(a.y + a.height, b.y + b.height)
    return left, top, max(0, right - left), max(0, bottom - top)


def dumps_ui(document):
    """Serialize a DocumentData into Qt Designer-compatible XML text."""
    root = ET.Element("ui", {"version": "4.0"})
    root.append(
        ET.Comment(
            f" Generated by {APP_MARKER} {__version__} - a PySide2 vacuum system studio. "
        )
    )
    ET.SubElement(root, "class").text = "VacuumSystem"

    top = ET.SubElement(root, "widget", {"class": "QWidget", "name": "VacuumSystem"})
    _add_rect(top, 0, 0, CANVAS_WIDTH, CANVAS_HEIGHT)
    _add_property(top, "windowTitle", document.project_name or "真空系统")
    _add_property(top, "app", APP_MARKER, dynamic=True)
    _add_property(top, "schemaVersion", 1, kind="number", dynamic=True)
    _add_property(top, "projectName", document.project_name or "未命名工程", dynamic=True)

    canvas = ET.SubElement(top, "widget", {"class": "QWidget", "name": "canvas"})
    _add_rect(canvas, 0, 0, CANVAS_WIDTH, CANVAS_HEIGHT)
    _add_property(canvas, "projectName", document.project_name or "未命名工程", dynamic=True)

    components_by_id = {c.object_id: c for c in document.components}
    for component in document.components:
        spec = DEVICE_SPECS.get(component.device_type)
        if spec is None:
            continue
        widget = ET.SubElement(
            canvas,
            "widget",
            {"class": spec.class_name, "name": component.object_id},
        )
        _add_rect(widget, component.x, component.y, component.width, component.height)
        _add_property(widget, "deviceId", component.object_id, dynamic=True)
        _add_property(widget, "deviceType", component.device_type, dynamic=True)
        _add_property(widget, "label", component.label, dynamic=True)
        _add_property(widget, "online", component.online, kind="bool", dynamic=True)
        _add_property(widget, "switchedOn", component.switched_on, kind="bool", dynamic=True)
        _add_property(widget, "targetSpeed", component.speed, kind="number", dynamic=True)
        _add_property(widget, "pressure", repr(float(component.pressure)), kind="double", dynamic=True)
        if component.device_type == "gate":
            _add_property(
                widget, "flangeAId", component.flange_a_id or "", dynamic=True
            )
            _add_property(
                widget, "flangeBId", component.flange_b_id or "", dynamic=True
            )

    for pipe in document.pipes:
        x, y, w, h = _pipe_bounds(pipe, components_by_id)
        widget = ET.SubElement(
            canvas,
            "widget",
            {"class": "VacuumPipe", "name": pipe.pipe_id},
        )
        _add_rect(widget, x, y, w, h)
        _add_property(widget, "sourceId", pipe.source_id, dynamic=True)
        _add_property(widget, "targetId", pipe.target_id, dynamic=True)
        _add_property(widget, "routeMode", pipe.route_mode, dynamic=True)
        _add_property(
            widget,
            "bendPoints",
            encode_bend_points(pipe.bend_points),
            dynamic=True,
        )

    customwidgets = ET.SubElement(root, "customwidgets")
    for key in PALETTE_ORDER:
        spec = DEVICE_SPECS[key]
        custom = ET.SubElement(customwidgets, "customwidget")
        ET.SubElement(custom, "class").text = spec.class_name
        ET.SubElement(custom, "extends").text = "QWidget"
        ET.SubElement(custom, "header").text = "torr_craft.components.devices"
    custom = ET.SubElement(customwidgets, "customwidget")
    ET.SubElement(custom, "class").text = "VacuumPipe"
    ET.SubElement(custom, "extends").text = "QWidget"
    ET.SubElement(custom, "header").text = "torr_craft.components.pipe"

    ET.SubElement(root, "resources")
    ET.SubElement(root, "connections")
    ET.SubElement(root, "slots")

    ET.indent(root, space="  ")
    xml = ET.tostring(root, encoding="unicode")
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + xml + "\n"


def _clean_id(raw, fallback):
    value = re.sub(r"[^A-Za-z0-9_]", "_", (raw or "").strip())
    if not value:
        value = fallback
    if not re.match(r"[A-Za-z_]", value):
        value = "d_" + value
    return value[:80]


def _unique_id(candidate, used):
    candidate = _clean_id(candidate, "item")
    if candidate not in used:
        used.add(candidate)
        return candidate
    index = 2
    while f"{candidate}_{index}" in used:
        index += 1
    result = f"{candidate}_{index}"
    used.add(result)
    return result


def _clamp_geometry(x, y, w, h, spec):
    min_w, min_h = spec.min_size
    w = max(min_w, min(CANVAS_WIDTH, int(w)))
    h = max(min_h, min(CANVAS_HEIGHT, int(h)))
    x = max(0, min(int(x), CANVAS_WIDTH - w))
    y = max(0, min(int(y), CANVAS_HEIGHT - h))
    return x, y, w, h


def loads_ui(text, fallback_name="未命名工程"):
    """Parse .ui XML into a DocumentData, validating component connections."""
    if not text or not text.strip():
        raise UiFormatError("文件为空")
    try:
        root = ET.fromstring(text)
    except ET.ParseError as exc:
        raise UiFormatError(f"XML 解析失败：{exc}") from exc

    if _local(root.tag) != "ui":
        raise UiFormatError("不是 Qt .ui 文件：根节点应为 <ui>")

    top_widget = None
    for candidate in root:
        if _local(candidate.tag) == "widget":
            top_widget = candidate
            break
    if top_widget is None:
        raise UiFormatError("Qt .ui 文件中缺少顶层 <widget>")

    app_marker = _prop_text(top_widget, "app", "")
    project_name = (
        _prop_text(top_widget, "projectName", "")
        or _prop_text(top_widget, "windowTitle", "")
        or fallback_name
        or "未命名工程"
    )
    project_name = project_name.strip()[:120] or "未命名工程"

    canvas_widget = None
    for widget in root.iter():
        if _local(widget.tag) == "widget" and widget.get("name") == "canvas":
            canvas_widget = widget
            break
    if canvas_widget is not None:
        canvas_name = _prop_text(canvas_widget, "projectName", "")
        if canvas_name:
            project_name = canvas_name[:120] or project_name

    widget_nodes = [w for w in root.iter() if _local(w.tag) == "widget"]
    known_widgets = []
    pipe_nodes = []
    for node in widget_nodes:
        cls = node.get("class", "")
        if cls in CLASS_TO_KEY:
            known_widgets.append(node)
        elif cls == "VacuumPipe":
            pipe_nodes.append(node)

    if len(known_widgets) > MAX_COMPONENTS:
        raise UiFormatError(f"元件数量超过上限（{MAX_COMPONENTS}）")
    if len(pipe_nodes) > MAX_PIPES:
        raise UiFormatError(f"管道数量超过上限（{MAX_PIPES}）")

    if not known_widgets and not pipe_nodes:
        if app_marker != APP_MARKER:
            raise UiFormatError(
                "文件中没有找到可识别的真空元件。"
                "请导入由 Torr Craft 导出的 .ui 文件。"
            )

    components = []
    pipes = []
    warnings = []
    used_ids = set()
    original_to_new = {}
    component_by_id = {}
    accepted_edges = []
    type_counts = {}

    for node in known_widgets:
        cls = node.get("class", "")
        fallback_type = CLASS_TO_KEY.get(cls)
        device_type = _prop_text(node, "deviceType", fallback_type or "")
        if device_type not in DEVICE_SPECS:
            warnings.append(f"跳过未知元件类型：{device_type or cls}")
            continue
        spec = DEVICE_SPECS[device_type]
        type_counts[device_type] = type_counts.get(device_type, 0) + 1
        raw_name = node.get("name") or _prop_text(node, "deviceId", "")
        object_id = _unique_id(raw_name, used_ids)
        if raw_name and object_id != raw_name:
            original_to_new.setdefault(raw_name, object_id)

        rect = _prop_rect(node)
        if rect is None:
            rect = (
                60 + (len(components) % 6) * 34,
                90 + (len(components) % 5) * 30,
                spec.default_size[0],
                spec.default_size[1],
            )
        x, y, w, h = _clamp_geometry(*rect, spec)
        label = _prop_text(node, "label", "")
        if not label:
            if device_type == "chamber":
                label = spec.default_label if type_counts[device_type] == 1 else f"腔室 {type_counts[device_type]:02d}"
            else:
                label = f"{spec.default_label.rsplit(' ', 1)[0]} {type_counts[device_type]:02d}"

        data = ComponentData(
            device_type=device_type,
            object_id=object_id,
            x=x,
            y=y,
            width=w,
            height=h,
            label=label[:80],
            online=_prop_bool(node, "online", True),
            switched_on=_prop_bool(node, "switchedOn", False),
            speed=max(0, min(spec.max_speed, _prop_int(node, "targetSpeed", spec.default_speed))),
            pressure=max(0.0, _prop_float(node, "pressure", 1.0e-5)),
            flange_a_id=(
                _prop_text(node, "flangeAId", "") if device_type == "gate" else ""
            ),
            flange_b_id=(
                _prop_text(node, "flangeBId", "") if device_type == "gate" else ""
            ),
        )
        components.append(data)
        component_by_id[object_id] = data

    # Resolve inline gate flange references after all object IDs are known.
    for component in components:
        if component.device_type != "gate":
            continue
        resolved = []
        for side, raw_id in (
            ("A", component.flange_a_id),
            ("B", component.flange_b_id),
        ):
            raw_id = raw_id or ""
            if not raw_id:
                resolved.append("")
                continue
            resolved_id = original_to_new.get(raw_id, _clean_id(raw_id, "missing"))
            target = component_by_id.get(resolved_id)
            if target is None:
                warnings.append(
                    f"插板阀 {component.label} 的 {side} 侧法兰指向不存在的元件：{raw_id}"
                )
                resolved.append("")
            elif target.device_type != "chamber":
                warnings.append(
                    f"插板阀 {component.label} 的 {side} 侧法兰只能连接腔室"
                )
                resolved.append("")
            else:
                resolved.append(resolved_id)
        if resolved[0] and resolved[0] == resolved[1]:
            warnings.append(f"插板阀 {component.label} 两侧不能是同一个腔室")
            resolved[1] = ""
        component.flange_a_id = resolved[0]
        component.flange_b_id = resolved[1]

    component_types = {component.object_id: component.device_type for component in components}
    for node in pipe_nodes:
        raw_source = _prop_text(node, "sourceId", "") or _prop_text(node, "source", "")
        raw_target = _prop_text(node, "targetId", "") or _prop_text(node, "target", "")
        source_id = original_to_new.get(raw_source, _clean_id(raw_source, "missing"))
        target_id = original_to_new.get(raw_target, _clean_id(raw_target, "missing"))
        if source_id not in component_by_id or target_id not in component_by_id:
            warnings.append(f"跳过断开的管道：{raw_source or '?'} → {raw_target or '?'}")
            continue
        if source_id == target_id:
            warnings.append("跳过指向自身的管道")
            continue
        source = component_by_id[source_id]
        target = component_by_id[target_id]
        if source.device_type == "gate" or target.device_type == "gate":
            warnings.append(
                f"插板阀已改为内联法兰，跳过旧版管道：{source.label} → {target.label}"
            )
            continue
        if source.device_type == "chamber" and target.device_type == "chamber":
            warnings.append(f"跳过未隔离的腔室直连管道：{source.label} → {target.label}")
            continue
        pair = frozenset((source_id, target_id))
        if any(frozenset((p.source_id, p.target_id)) == pair for p in pipes):
            warnings.append(f"跳过重复管道：{source.label} → {target.label}")
            continue

        bypass = unisolated_chamber_pair(
            component_types, accepted_edges + [(source_id, target_id)]
        )
        if bypass is not None:
            first = component_by_id.get(bypass[0])
            second = component_by_id.get(bypass[1])
            conflict = " ↔ ".join(
                item.label if item else object_id
                for item, object_id in ((first, bypass[0]), (second, bypass[1]))
            )
            warnings.append(
                f"跳过会绕过插板阀的管道：{source.label} → {target.label}（{conflict} 会失去隔离）"
            )
            continue

        route_mode = _prop_text(node, "routeMode", "auto") or "auto"
        if route_mode not in ROUTE_MODES:
            warnings.append(
                f"管道 {source.label} → {target.label} 的路由方式无效，已改为自动正交"
            )
            route_mode = "auto"
        raw_bends = _prop_text(node, "bendPoints", "")
        bend_points = []
        invalid_bends = 0
        for x, y in decode_bend_points(raw_bends):
            if 0 <= x <= CANVAS_WIDTH and 0 <= y <= CANVAS_HEIGHT:
                bend_points.append((x, y))
            else:
                invalid_bends += 1
                bend_points.append(
                    (
                        max(0, min(CANVAS_WIDTH, x)),
                        max(0, min(CANVAS_HEIGHT, y)),
                    )
                )
        if invalid_bends:
            warnings.append(
                f"管道 {source.label} → {target.label} 有 {invalid_bends} 个拐点超出画布，已裁剪"
            )

        raw_pipe_id = node.get("name", "")
        pipe_id = _unique_id(raw_pipe_id or f"pipe_{len(pipes) + 1}", used_ids)
        pipes.append(
            PipeData(
                pipe_id=pipe_id,
                source_id=source_id,
                target_id=target_id,
                route_mode=route_mode,
                bend_points=bend_points,
            )
        )
        accepted_edges.append((source_id, target_id))

    if not components and pipe_nodes:
        raise UiFormatError("文件中的管道没有有效端点，无法导入")

    return DocumentData(
        project_name=project_name,
        components=components,
        pipes=pipes,
        warnings=warnings,
    )


def read_ui_file(path):
    path = Path(path)
    try:
        size = path.stat().st_size
    except OSError as exc:
        raise UiFormatError(f"无法读取文件：{exc}") from exc
    if size > MAX_FILE_BYTES:
        raise UiFormatError("文件过大（上限 8 MB）")
    try:
        text = path.read_text(encoding="utf-8-sig")
    except UnicodeDecodeError as exc:
        raise UiFormatError("文件不是 UTF-8 编码") from exc
    except OSError as exc:
        raise UiFormatError(f"无法读取文件：{exc}") from exc
    return loads_ui(text, fallback_name=path.stem)


def write_ui_file(document, path):
    path = Path(path)
    if path.suffix.lower() != ".ui":
        path = path.with_suffix(".ui")
    text = dumps_ui(document)
    parent = path.parent
    if not parent.exists():
        raise UiFormatError(f"目标目录不存在：{parent}")
    fd, temporary = tempfile.mkstemp(prefix=".torr-craft-", suffix=".ui.tmp", dir=str(parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise
    return path
